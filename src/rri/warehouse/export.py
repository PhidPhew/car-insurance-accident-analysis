"""Export the built warehouse to `data/40_exports/` (Phase 4 Step 6).

CLAUDE.md's submission requirements need the warehouse in forms that don't
require DuckDB to open: Parquet + CSV per table (for anyone with pandas/
Excel), plus a MySQL DDL script + loader (`schema_mysql.sql` /
`load_to_mysql.py`) so the whole warehouse can stand up on a plain MySQL
instance too.
"""

from __future__ import annotations

from pathlib import Path

import duckdb

from rri.utils.logging import get_logger

log = get_logger(__name__)

#: Surrogate/primary key per table -- used for the MySQL DDL's PRIMARY KEY clause.
TABLE_PRIMARY_KEYS = {
    "dim_date": "date_sk",
    "dim_geography": "geography_sk",
    "dim_vehicle": "vehicle_sk",
    "dim_accident_context": "accident_context_sk",
    "dim_time_of_day": "time_of_day_sk",
    "dim_weather_band": "weather_band_sk",
    "dim_policy_type": "policy_type_sk",
    "dim_customer_segment": "customer_segment_sk",
    "fact_accident": "accident_sk",
    "fact_underwriting_monthly": "underwriting_sk",
}

#: DuckDB `DESCRIBE` type -> MySQL 8 type. `VARCHAR` maps to `TEXT` rather
#: than a fixed-length `VARCHAR(n)` -- several columns hold Thai free text
#: (e.g. `agency`, `road_code`) with no natural length cap to pick safely.
_DUCKDB_TO_MYSQL_TYPE = {
    "BIGINT": "BIGINT",
    "INTEGER": "INT",
    "SMALLINT": "SMALLINT",
    "TINYINT": "TINYINT",
    "UBIGINT": "BIGINT UNSIGNED",
    "UINTEGER": "INT UNSIGNED",
    "DOUBLE": "DOUBLE",
    "FLOAT": "FLOAT",
    "VARCHAR": "TEXT",
    "BOOLEAN": "BOOLEAN",
    "DATE": "DATE",
    "TIME": "TIME",
    "TIMESTAMP": "DATETIME",
}


def _mysql_type_for(duckdb_type: str) -> str:
    base = duckdb_type.split("(")[0].strip().upper()
    return _DUCKDB_TO_MYSQL_TYPE.get(base, "TEXT")


def export_table_files(con: duckdb.DuckDBPyConnection, table_name: str, export_dir: Path) -> None:
    """Write `table_name` to `{export_dir}/{table_name}.parquet` and `.csv`."""
    export_dir.mkdir(parents=True, exist_ok=True)
    parquet_path = export_dir / f"{table_name}.parquet"
    csv_path = export_dir / f"{table_name}.csv"
    con.sql(f"COPY \"{table_name}\" TO '{parquet_path}' (FORMAT PARQUET)")
    con.sql(f"COPY \"{table_name}\" TO '{csv_path}' (FORMAT CSV, HEADER TRUE)")
    log.info("exported_table", table=table_name, parquet=str(parquet_path), csv=str(csv_path))


def generate_mysql_schema(con: duckdb.DuckDBPyConnection, table_names: list[str]) -> str:
    """Build `CREATE TABLE` DDL for every table, in MySQL 8 dialect."""
    statements = [
        "-- Auto-generated by rri.warehouse.export.generate_mysql_schema -- do not hand-edit.",
        "-- Regenerate via `uv run python -m rri.warehouse.export`.",
        "",
    ]
    for table_name in table_names:
        columns = con.sql(f'DESCRIBE "{table_name}"').pl()
        column_names = set(columns["column_name"].to_list())
        primary_key = TABLE_PRIMARY_KEYS.get(table_name)
        column_lines = [
            f"  `{row['column_name']}` {_mysql_type_for(row['column_type'])}"
            for row in columns.iter_rows(named=True)
        ]
        if primary_key and primary_key in column_names:
            column_lines.append(f"  PRIMARY KEY (`{primary_key}`)")
        statements.append(f"CREATE TABLE IF NOT EXISTS `{table_name}` (")
        statements.append(",\n".join(column_lines))
        statements.append(");")
        statements.append("")
    return "\n".join(statements)


def export_all(con: duckdb.DuckDBPyConnection, export_dir: Path, table_names: list[str]) -> None:
    """Export every table to Parquet/CSV, plus a MySQL schema file."""
    for table_name in table_names:
        export_table_files(con, table_name, export_dir)

    schema_sql = generate_mysql_schema(con, table_names)
    schema_path = export_dir / "schema_mysql.sql"
    schema_path.write_text(schema_sql, encoding="utf-8")
    log.info("wrote_mysql_schema", path=str(schema_path))


def run_export() -> None:
    """Export every table already in `warehouse.duckdb` to `data/40_exports/`."""
    from config.settings import settings
    from rri.utils.logging import configure_logging
    from rri.warehouse.duckdb_io import get_connection

    configure_logging()
    settings.ensure_writable_dirs()
    con = get_connection()
    try:
        table_names = list(TABLE_PRIMARY_KEYS.keys())
        export_all(con, settings.exports_dir, table_names)
    finally:
        con.close()


if __name__ == "__main__":
    run_export()
