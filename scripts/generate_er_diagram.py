"""Generate the star-schema ER diagram into `reports/` (Phase 4 Step 6).

Introspects the built `warehouse.duckdb` for each table's columns/types
(so the diagram can't silently drift from the real schema), combined with
the FK relationships CLAUDE.md §8 defines -- DuckDB doesn't store these as
enforced foreign keys (a deliberate choice: N7's Unknown Member pattern
means a fact row's FK is always valid by construction, so a DB-level FK
constraint would add nothing but rigidity), so the relationship list itself
is maintained here, not discovered.

Run: ``uv run python scripts/generate_er_diagram.py``
Output: ``reports/er_diagram.md`` (Mermaid `erDiagram`, renders natively on
GitHub and in most Markdown viewers).
"""

from __future__ import annotations

import sys
from pathlib import Path

import duckdb

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from config.settings import settings  # noqa: E402
from rri.utils.logging import configure_logging, get_logger  # noqa: E402
from rri.warehouse.duckdb_io import get_connection  # noqa: E402
from rri.warehouse.export import TABLE_PRIMARY_KEYS  # noqa: E402

log = get_logger(__name__)

#: (fact table, FK column, dimension table) -- CLAUDE.md §8's star schema.
#: `agency` is deliberately absent: a degenerate attribute on fact_accident,
#: not a dimension FK (see CLAUDE.md §8 / the Phase 3 checkpoint report).
RELATIONSHIPS: list[tuple[str, str, str]] = [
    ("fact_accident", "date_sk", "dim_date"),
    ("fact_accident", "time_of_day_sk", "dim_time_of_day"),
    ("fact_accident", "geography_sk", "dim_geography"),
    ("fact_accident", "vehicle_sk", "dim_vehicle"),
    ("fact_accident", "accident_context_sk", "dim_accident_context"),
    ("fact_accident", "weather_band_sk", "dim_weather_band"),
    ("fact_underwriting_monthly", "date_sk", "dim_date"),
    ("fact_underwriting_monthly", "geography_sk", "dim_geography"),
    ("fact_underwriting_monthly", "vehicle_sk", "dim_vehicle"),
    ("fact_underwriting_monthly", "policy_type_sk", "dim_policy_type"),
]

_MERMAID_SAFE_TYPE = {
    "VARCHAR": "string",
    "BOOLEAN": "boolean",
    "DATE": "date",
    "TIME": "time",
    "TIMESTAMP": "datetime",
}


def _mermaid_type(duckdb_type: str) -> str:
    base = duckdb_type.split("(")[0].strip().upper()
    return _MERMAID_SAFE_TYPE.get(base, base.lower())


def _entity_block(con: duckdb.DuckDBPyConnection, table_name: str) -> str:
    columns = con.sql(f'DESCRIBE "{table_name}"').pl()
    primary_key = TABLE_PRIMARY_KEYS.get(table_name)
    lines = [f"    {table_name} {{"]
    for row in columns.iter_rows(named=True):
        col = row["column_name"]
        col_type = _mermaid_type(row["column_type"])
        marker = " PK" if col == primary_key else ""
        lines.append(f"        {col_type} {col}{marker}")
    lines.append("    }")
    return "\n".join(lines)


def generate_er_diagram_markdown(con: duckdb.DuckDBPyConnection) -> str:
    table_names = list(TABLE_PRIMARY_KEYS.keys())
    entity_blocks = "\n".join(_entity_block(con, t) for t in table_names)
    relationship_lines = "\n".join(
        f'    {dim} ||--o{{ {fact} : "{fk}"' for fact, fk, dim in RELATIONSHIPS
    )

    return f"""# Warehouse ER Diagram (CLAUDE.md §8)

Auto-generated by `scripts/generate_er_diagram.py` from the live
`warehouse.duckdb` schema -- regenerate after any dimension/fact change
rather than hand-editing.

Conformed dimensions `dim_date` and `dim_geography` are shared by both
facts (Kimball bus architecture) -- note both appear on the left of two
relationships below. `agency` is a degenerate attribute on `fact_accident`
(not shown as a relationship -- it has no dimension table, CLAUDE.md §8).

```mermaid
erDiagram
{entity_blocks}

{relationship_lines}
```
"""


def main() -> None:
    configure_logging()
    con = get_connection()
    try:
        markdown = generate_er_diagram_markdown(con)
    finally:
        con.close()

    output_path = settings.reports_dir / "er_diagram.md"
    settings.reports_dir.mkdir(parents=True, exist_ok=True)
    output_path.write_text(markdown, encoding="utf-8")
    log.info("wrote_er_diagram", path=str(output_path))


if __name__ == "__main__":
    main()
